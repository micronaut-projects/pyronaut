"""Install Python runtime packages for Pyronaut deployment artifacts."""

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from . import cli


def _copy_runtime_libraries(executable: Path) -> None:
    """Distroless base images omit the C++ runtime needed by standalone GraalPy."""
    glibc = {"libc.so.6", "libm.so.6", "libdl.so.2", "libpthread.so.0", "librt.so.1", "libresolv.so.2", "libutil.so.1"}
    target = cli._data_home() / "lib"
    target.mkdir(exist_ok=True)
    for line in subprocess.check_output(["ldd", str(executable)], text=True).splitlines():
        _, separator, location = line.partition(" => ")
        if separator and location.startswith("/"):
            source = Path(location.split(" (", 1)[0])
            if source.name not in glibc:
                shutil.copy2(source, target / source.name)


def provision() -> cli._GraalPyInstallation:
    """Provision once in a Docker layer that can survive dependency changes."""
    spec = cli._required_graalpy()
    if spec is None:
        raise RuntimeError("The Docker dependency builder is missing GraalPy version metadata")
    installation = cli._find_graalpy(spec) or cli._download_and_install_graalpy(spec)
    if installation is None:
        raise RuntimeError("The downloaded Docker GraalPy interpreter does not match the SDK")
    _copy_runtime_libraries(installation.executable)
    return installation


def install(project: Path, requirements: list[str], *, uv: bool,
            python: Path | None = None, venv: Path | None = None, offline: bool = False) -> None:
    """Install runtime dependencies with the SDK's matching standalone GraalPy."""
    python = python or provision().executable
    venv = venv or cli._data_home() / "venv"
    env = dict(os.environ)
    env.pop("VIRTUAL_ENV", None)
    env.pop("PYTHONHOME", None)
    subprocess.run([str(python), "-m", "venv", str(venv)], env=env, check=True)
    python = venv / "bin" / "python"
    if offline:
        env["UV_OFFLINE"] = "true"
        env["PIP_NO_INDEX"] = "1"
    if uv:
        env["UV_PROJECT_ENVIRONMENT"] = str(venv)
        env["UV_PYTHON_DOWNLOADS"] = "never"
        command = ["uv", "sync", "--locked", "--no-dev", "--no-default-groups", "--no-install-project",
                   "--no-editable", "--python", str(python)]
    else:
        command = [str(python), "-m", "pip", "install", "--disable-pip-version-check", "--no-cache-dir"]
        if (project / "requirements.txt").is_file():
            command.extend(["-r", "requirements.txt"])
        command.extend(requirements)
    subprocess.run(command, cwd=project, env=env, check=True)
    if not cli._virtualenv_is_graalpy(python):
        raise RuntimeError("The Python dependency installer replaced GraalPy with another interpreter")


def package(venv: Path, classes: Path) -> None:
    """Embed packages in the VFS already used by Micronaut's GraalPy contexts."""
    root = classes / "META-INF/GRAALPY-VFS/micronaut-application"
    target = root / "venv"
    target.mkdir(parents=True, exist_ok=True)
    for name in ("lib", "Lib"):
        if (venv / name).is_dir():
            shutil.copytree(venv / name, target / name, dirs_exist_ok=True,
                            ignore=shutil.ignore_patterns("__pycache__"))
    shutil.copy2(venv / "pyvenv.cfg", target / "pyvenv.cfg")
    (target / "pyronaut-packaged.txt").write_text("Python runtime dependencies\n", encoding="utf-8")
    spec = cli._required_graalpy()
    (target / "contents").write_text((spec.version if spec and spec.version else "GraalPy") + "\n", encoding="utf-8")
    metadata = subprocess.check_output([
        str(venv / "bin/python"), "-c",
        "import importlib.metadata; print('\\n'.join(sorted(f'{d.metadata[\"Name\"]}=={d.version}' for d in importlib.metadata.distributions())))",
    ], text=True)
    (target / "installed.txt").write_text(metadata, encoding="utf-8")
    write_files_list(classes)


def write_files_list(classes: Path) -> None:
    root = classes / "META-INF/GRAALPY-VFS/micronaut-application"
    (root / "fileslist.txt").write_text("".join(
        "/" + path.relative_to(classes).as_posix() + "\n"
        for path in sorted(root.rglob("*")) if path.is_file() and path != root / "fileslist.txt"
    ), encoding="utf-8")


def remove_packaged_environment(classes: Path) -> None:
    """Remove only environments generated by the artifact packager."""
    venv = classes / "META-INF/GRAALPY-VFS/micronaut-application/venv"
    if (venv / "pyronaut-packaged.txt").is_file():
        shutil.rmtree(venv)
        write_files_list(classes)


def main() -> None:
    config = json.loads(Path("/python-builder/dependencies.json").read_text(encoding="utf-8"))
    install(Path("/python-project") / config["project"], config["requirements"], uv=config["uv"])


if __name__ == "__main__":
    if sys.argv[1:] == ["provision"]:
        provision()
    else:
        main()
